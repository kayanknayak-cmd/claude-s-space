# Writes INDEX.md: what is inside every Kenney zip in this folder, read straight from the zips.
# Run after adding packs: python3 assets/kenney/make-index.py
import os, re, zipfile
from collections import defaultdict

DIR = os.path.dirname(os.path.abspath(__file__))
out = ['# Kenney packs (generated by make-index.py, do not edit by hand)', '',
       'All CC0. Per pack: size, then the model names (GLB, one per model), sound names, or 2D folders.',
       'Numbered variants are collapsed: `impactWood_heavy_000..004` is listed once as `impactWood_heavy x5`.', '']

def collapse(names):
    groups = defaultdict(int)
    for n in names:
        groups[re.sub(r'[_-]?\d{2,3}$', '', n)] += 1
    return ', '.join(k + (f' x{v}' if v > 1 else '') for k, v in sorted(groups.items()))

for z in sorted(f for f in os.listdir(DIR) if f.endswith('.zip')):
    with zipfile.ZipFile(os.path.join(DIR, z)) as zf:
        files = [i.filename for i in zf.infolist() if not i.is_dir()]
    mb = os.path.getsize(os.path.join(DIR, z)) / 1048576
    glb = sorted({os.path.basename(f)[:-4] for f in files if f.lower().endswith('.glb')})
    snd = sorted({os.path.splitext(os.path.basename(f))[0] for f in files if f.lower().endswith(('.ogg', '.wav', '.mp3'))})
    png = [f for f in files if f.lower().endswith('.png')]
    out.append(f'## {z[:-4]} ({mb:.1f} MB)')
    if glb:
        glbdir = sorted({os.path.dirname(f) for f in files if f.lower().endswith('.glb')})
        out.append(f'{len(glb)} models in `{glbdir[0]}`: ' + collapse(glb))
    if snd:
        out.append(f'{len(snd)} sounds: ' + collapse(snd))
    if not glb and not snd:
        dirs = sorted({'/'.join(f.split('/')[:2]) for f in png if '/' in f})
        out.append(f'{len(png)} images. Folders: ' + ', '.join(dirs[:12]) + (' ...' if len(dirs) > 12 else ''))
    out.append('')

open(os.path.join(DIR, 'INDEX.md'), 'w').write('\n'.join(out))
print('wrote INDEX.md,', sum(1 for l in out if l.startswith('## ')), 'packs')
